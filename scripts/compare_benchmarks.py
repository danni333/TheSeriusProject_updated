#!/usr/bin/env python3
"""Compare TheSeriusProject bench results against llama.cpp (llama-bench).

Usage:
    python scripts/compare_benchmarks.py \
        --serius results_serius.json \
        --llamacpp results_llamacpp.json \
        --output comparison.md

`results_serius.json` is produced by `serius bench -f json`.
`results_llamacpp.json` is produced by `llama-bench -o json`.
"""
import argparse
import json
import sys


def load_json(path):
    with open(path) as f:
        return json.load(f)


def serius_metrics(data):
    """Flatten a `serius bench -f json` report into comparable metrics."""
    lat = data.get("latency", {})
    thr = data.get("throughput", {})
    mem = data.get("memory", {})
    return {
        "decode_tps": lat.get("decode_tps"),
        "prefill_tps": lat.get("prefill_tps"),
        "ttft_ms": lat.get("ttft_ms"),
        "total_tokens_per_sec": thr.get("total_tokens_per_sec"),
        "vram_peak_gb": (mem.get("vram_peak_bytes") or 0) / 2**30 or None,
    }


def llamacpp_metrics(data):
    """Extract pp/tg throughput from llama-bench -o json output.

    llama-bench emits a list of test objects; we match on n_prompt/n_gen
    and take avg_ts (tokens/sec). Falls back to the first entries.
    """
    if not isinstance(data, list):
        return {}
    pp = tg = None
    for entry in data:
        ts = entry.get("avg_ts")
        np_ = entry.get("n_prompt", 0)
        ng = entry.get("n_gen", 0)
        if ts is None:
            continue
        # llama-bench marks prompt-processing tests with n_gen == 0
        if ng == 0 and np_ > 0 and (pp is None or np_ > pp[0]):
            pp = (np_, ts)
        elif ng > 0 and (tg is None or ng > tg[0]):
            tg = (ng, ts)
    out = {}
    if pp:
        out["prefill_tps"] = pp[1]
    if tg:
        out["decode_tps"] = tg[1]
    return out


def delta_pct(serius, other):
    if serius is None or other in (None, 0):
        return None
    return (serius - other) / other * 100.0


def fmt(v, suffix=""):
    return "n/a" if v is None else f"{v:.2f}{suffix}"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--serius", required=True, help="serius bench JSON report")
    ap.add_argument("--llamacpp", required=True, help="llama-bench JSON output")
    ap.add_argument("--output", default="-", help="output markdown file ('-' for stdout)")
    args = ap.parse_args()

    s = serius_metrics(load_json(args.serius))
    l = llamacpp_metrics(load_json(args.llamacpp))

    rows = [
        ("Decode TPS (tok/s)", s.get("decode_tps"), l.get("decode_tps"), "higher is better"),
        ("Prefill TPS (tok/s)", s.get("prefill_tps"), l.get("prefill_tps"), "higher is better"),
        ("TTFT (ms)", s.get("ttft_ms"), None, "lower is better"),
        ("Batch tok/s", s.get("total_tokens_per_sec"), None, "higher is better"),
        ("Peak VRAM (GB)", s.get("vram_peak_gb"), None, "lower is better"),
    ]

    lines = [
        "# Benchmark comparison: Serius vs llama.cpp",
        "",
        "| Metric | Serius | llama.cpp | Delta | Note |",
        "|--------|--------|-----------|-------|------|",
    ]
    for name, sv, lv, note in rows:
        d = delta_pct(sv, lv) if lv is not None else None
        dstr = "n/a" if d is None else f"{d:+.1f}%"
        lines.append(f"| {name} | {fmt(sv)} | {fmt(lv)} | {dstr} | {note} |")
    lines.append("")
    lines.append("_Generated by scripts/compare_benchmarks.py_")
    out = "\n".join(lines) + "\n"

    if args.output == "-":
        sys.stdout.write(out)
    else:
        with open(args.output, "w") as f:
            f.write(out)
        print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
